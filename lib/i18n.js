let current = 'uz';

function normalize(lang) {
  const l = String(lang || '').toLowerCase().slice(0, 2);
  return LANGS.includes(l) ? l : null;
}

/** Picks the first supported language (uz/ru/en) from the candidates; falls back to Uzbek. */
function detect(...candidates) {
  for (const c of candidates) {
    const l = normalize(c);
    if (l) return l;
  }
  return 'uz';
}

function setLang(lang) {
  current = normalize(lang) || current;
  return current;
}

function getLang() {
  return current;
}

function t(key, params) {
  if (params && params.n === 1 && D[`${key}.one`]) key = `${key}.one`;
  const row = D[key];
  let s = row ? row[LANGS.indexOf(current)] ?? row[2] : key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
  return s;
}

module.exports = { LANGS, LANG_NAMES, detect, getLang, setLang, t, DICTIONARY: D };
